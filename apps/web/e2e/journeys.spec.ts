for (const path of ['/login', '/app', '/app/alerts', '/app/hunt', '/app/detections', '/app/response', '/app/reports']) {
  test(`a11y: no serious axe violations on ${path}`, async ({ page }) => {
    if (path !== '/login') { await login(page, 'analyst'); await page.goto(path) } else await page.goto(path)
    await page.waitForTimeout(700)
    const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag22aa']).analyze()
    const bad = r.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')
    expect(bad.map((v) => `${v.id}: ${v.nodes[0]?.html.slice(0, 120)}`)).toEqual([])
  })
}

