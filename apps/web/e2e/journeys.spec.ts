test('Journey 2: triage -> case -> notes -> resolve -> close -> reopen -> report', async ({ page, browser }) => {
  test.setTimeout(120_000)
  await login(page, 'analyst')
  await runDemo(page)
  await page.goto('/app/alerts')
  await page.getByRole('link', { name: /Repeated failed sign-ins/ }).first().click()
  await page.getByRole('button', { name: 'Create case' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Create case' }).click()
  await expect(page).toHaveURL(/incidents\/\d+/)
  await expect(page.getByText('Guided investigation')).toBeVisible()
  await page.getByRole('button', { name: 'Add note' }).click()
  await page.getByLabel('Note', { exact: true }).fill('7 failures then success, synthetic')
  await page.getByRole('dialog').getByRole('button', { name: 'Add note' }).click()
  await expect(page.getByText('7 failures then success, synthetic').first()).toBeVisible()
  await page.getByRole('button', { name: /→ Triage/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click()
  await page.getByRole('button', { name: /→ Investigating/ }).first().click()
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click()
  await page.getByRole('button', { name: /→ Resolved/ }).click()
  await page.getByLabel('Resolution').selectOption('TEST_ACTIVITY')
  await page.getByLabel(/Note \(required\)/).fill('Expected synthetic exercise')
  await page.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click()
  await expect(page.getByText('Expected test activity').first()).toBeVisible()
  // report export is built from stored records
  const dl = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export report' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Markdown' }).click()
  expect((await dl).suggestedFilename()).toMatch(/incident-\d+-redacted\.md/)
  // lead closes then reopens
  const ctx = await browser.newContext(); const lp = await ctx.newPage()
  await login(lp, 'lead')
  await lp.goto(page.url())
  await lp.getByRole('button', { name: /→ Closed/ }).click()
  await lp.getByLabel('Note (required)').fill('Reviewed, closing')
  await lp.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click()
  await expect(lp.getByText('Closed').first()).toBeVisible()
  await lp.getByRole('button', { name: 'Reopen' }).click()
  await lp.getByLabel(/Note \(required\)/).fill('New evidence')
  await lp.getByRole('dialog').getByRole('button', { name: 'Confirm' }).click()
  await expect(lp.getByText('CLOSED → INVESTIGATING').first()).toBeVisible()
  await ctx.close()
})

